# 页级绑定规则：凡出现左侧任一「敞口敏感的数字」的页面，同页必须出现右侧任一「门槛关键词」。
# deck 级校验只能保证全册提到过门槛，无法阻止单页把有条件结论讲成无条件结论。
PAGE_BOUND_RULES = [
    (["0.46次", "0.24次", "2.8倍", "约6倍"], ["u×s", "门槛", "反转"]),
    (["4.22倍", "0.357次"], ["u×s", "成立边界", "反转"]),
    (["11.63倍"], ["1.28倍"]),
    (["低估2~3倍", "低估2至3倍"], ["每轮产出", "每轮对话产出"]),
]


def check_pages():
    problems = []
    for page, texts in page_text.items():
        joined = "".join(texts)
        for triggers, required in PAGE_BOUND_RULES:
            if any(t in joined for t in triggers) and not any(r in joined for r in required):
                hit = next(t for t in triggers if t in joined)
                problems.append(f"第{page}页出现「{hit}」但同页未出现门槛/边界关键词{required}")
    return problems


def check_stance(text):
    problems = check_pages()
    if "**" in text:
        problems.append("渲染文本含 markdown 星号（PPT 不渲染 markdown，应改用书名号）")
    for name, required, forbidden in STANCE_RULES:
        for kw in required:
            if kw not in text:
                problems.append(f"缺少限定语「{kw}」（规则：{name}）")
        for kw in forbidden:
            if kw in text:
                problems.append(f"出现被禁表述「{kw}」（规则：{name}）")
    if problems:
        raise SystemExit("PPT 与报告立场不一致，生成中止：\n  - " + "\n  - ".join(problems))
    print(f"立场一致性校验通过（{len(STANCE_RULES)} 条规则）")


