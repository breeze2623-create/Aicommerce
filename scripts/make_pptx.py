def set_font(run, size=14, bold=False, color=INK):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run.font.name = FONT
    rPr = run._r.get_or_add_rPr()
    ea = rPr.find(qn("a:ea"))
    if ea is None:
        ea = rPr.makeelement(qn("a:ea"), {})
        rPr.append(ea)
    ea.set("typeface", FONT)


def box(slide, x, y, w, h, lines, align=PP_ALIGN.LEFT):
    """lines 元素为 (文本, 字号, 加粗, 颜色) 或 (文本, 字号, 加粗, 颜色, 段后距pt)。"""
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    first = True
    for item in lines:
        text, size, bold, color = item[:4]
        space_after = item[4] if len(item) > 4 else max(3, size * 0.3)
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        p.alignment = align
        run = p.add_run()
        run.text = text
        set_font(run, size=size, bold=bold, color=color)
        p.space_after = Pt(space_after)
    return tb


def _visual_len(text):
    """CJK字符按1个字宽计，其余按0.6个字宽计。"""
    return sum(1.0 if ord(c) > 0x2E7F else 0.6 for c in text)


def rect(slide, x, y, w, h, fill):
    sh = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, x, y, w, h)
    sh.fill.solid()
    sh.fill.fore_color.rgb = fill
    sh.line.fill.background()
    sh.shadow.inherit = False
    return sh


